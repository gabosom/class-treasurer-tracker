export type Dict = typeof es;
export const dictionaries: Record<Lang, Dict> = { es, en };

export function toLang(v: string | undefined): Lang {
  return v === "en" ? "en" : "es";
}

export function formatDate(iso: string | null, lang: Lang): string {
  if (!iso) return "";
  return new Date(iso + "T12:00:00Z").toLocaleDateString(lang === "es" ? "es-US" : "en-US", {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  });
}
